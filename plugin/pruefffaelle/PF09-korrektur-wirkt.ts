const S = "agent:seneca:main";

test("PF09 Korrektur ändert genau eine Stelle, ist zurücknehmbar, Wiederholung wird gezählt, Skill steht im Start-Kontext", async () => {
  const p = ladePlugin();
  um("10:00");
  const zaehle = () => ereignisse(p.db, { grenze: -1 }).filter((e) => ["wert.gesetzt", "auftrag.angelegt"].includes(String(e.art))).length;
  p.nachricht(S, "m1", "Schick Links immer mit, bitte immer mit Link");
  const vorher = zaehle();
  const r = await p.werkzeug("seneca_lernen", S, "seneca", { nachricht_kennung: "m1", wortlaut: "immer mit Link", ort: "profil", ziel: "Links in Antworten", kern: "immer mit Link", aenderung: { schluessel: "profil:links", wert: "immer" } });
  assert.match(r.zeile, /^Gelernt: /);
  assert.equal(zaehle() - vorher, 1);
  assert.equal(wert(p.db, "profil:links")?.wert, "immer");
  p.methode("seneca.handeln", { kennung: "z1", geraet: "iphone", art: "lernen.zuruecknehmen", ziel: String(r.korrektur_nr) });
  assert.equal(wert(p.db, "profil:links")?.wert, "");
  p.nachricht(S, "m2", "Keine Mails an Kunden nach 20 Uhr");
  const vorSperre = auftraege(p.db, ["bereit"]).length;
  await p.werkzeug("seneca_lernen", S, "seneca", { nachricht_kennung: "m2", wortlaut: "Keine Mails an Kunden nach 20 Uhr", ort: "sperre", ziel: "Ausgang Mail", kern: "keine Kundenmail nach 20 Uhr", aenderung: {} });
  assert.equal(auftraege(p.db, ["bereit"]).length - vorSperre, 1);
  p.nachricht(S, "m3", "Wie oft noch: immer mit Link");
  const w = await p.werkzeug("seneca_lernen", S, "seneca", { nachricht_kennung: "m3", wortlaut: "Wie oft noch: immer mit Link", ort: "skill", ziel: "mail_an_kunden", kern: "immer mit Link", aenderung: { skill: "mail_an_kunden", alt: "Schritt 3: kurz.", neu: "Schritt 3: kurz, immer mit Link." } });
  assert.equal(Number(w.wiederholungen_woche), 1);
  assert.ok(auftraege(p.db, ["bereit"]).some((a) => String(a.titel).startsWith("Wiederholung untersuchen")));
  const zustand = mkdtempSync(join(tmpdir(), "seneca-zustand-"));
  const werkstatt = join(zustand, "agents", "produkt", "agent", "workshop-skills", "mail-an-kunden");
  mkdirSync(werkstatt, { recursive: true });
  writeFileSync(join(werkstatt, "SKILL.md"), "Schritt 3: kurz, immer mit Link.");
  process.env.OPENCLAW_STATE_DIR = zustand;
  const a = auftragVonAntonio(p.db, "Mail an Kunden zum Angebot", { arbeitsart: "mail_an_kunden" });
  spaeter(6000);
  nurWach(p.db, "produkt");
  await faelligeAuftraegeJob(p.db, p.starte);
  assert.ok(p.kontext(String(laeufe(p.db, a)[0].sitzung))?.includes("Schritt 3: kurz, immer mit Link."));
});

test("PF09 Satz beim Nachbessern wird gelernt; ähnliche zuerst; Skill höchstens eine Zeile mehr; Zurücknehmen einmal, auch nach gebauter Sperre", async () => {
  const p = ladePlugin();
  um("10:00");
  nurWach(p.db, "produkt");
  const a = auftragVonAntonio(p.db, "Recherche zu Boardinghouse-Preisen", { arbeitsart: "recherchieren" });
  spaeter(6000);
  await faelligeAuftraegeJob(p.db, p.starte);
  const erster = String(laeufe(p.db, a)[0].sitzung);
  await p.werkzeug("seneca_fortschreiben", erster, "produkt", { letzter_stand: "Preise gesammelt", naechster_schritt: "Abnahme", ergebnis: "fertig", beleg: "Ablage/preise.md" });
  p.ende(erster);
  assert.equal(hole(p.db, "auftrag", a).zustand, "wartet_auf_abnahme");
  p.methode("seneca.handeln", { kennung: "nb1", geraet: "mac", art: "abnahme.nachbessern", ziel: a, wert: "Bitte immer mit Quellenangabe" });
  await faelligeAuftraegeJob(p.db, p.starte);
  const sitzung = String(laeufe(p.db, a).at(-1)?.sitzung);
  assert.match(String(p.kontext(sitzung)), /Kennung nb1\): „Bitte immer mit Quellenangabe“/);
  const lerne = (k: object) => p.werkzeug("seneca_lernen", sitzung, "produkt", { nachricht_kennung: "nb1", wortlaut: "immer mit Quellenangabe", ziel: "recherchieren", ...k });
  assert.match(String((await lerne({ ort: "skill", kern: "Quellen nennen", aenderung: { alt: "Schritt 2: suchen.", neu: "Schritt 2: suchen.\nZeile 1\nZeile 2" } })).fehler), /höchstens um eine Zeile/);
  const r = await lerne({ ort: "skill", kern: "Quellen nennen", aenderung: { alt: "Schritt 2: suchen.", neu: "Schritt 2: suchen, jede Zahl mit Quelle." } });
  assert.match(String(r.zeile), /^Gelernt: Skill „recherchieren“/);
  p.nachricht(S, "m9", "Bei Recherchen nenn immer die Quellen dazu");
  const zweite = await p.werkzeug("seneca_lernen", S, "seneca", { nachricht_kennung: "m9", wortlaut: "nenn immer die Quellen", ort: "profil", ziel: "Quellen in Recherchen", kern: "Quellen nennen", aenderung: { schluessel: "profil:quellen", wert: "immer" } });
  assert.deepEqual(zweite.aehnliche, [`${r.korrektur_nr}: Quellen nennen`]);
  const stand = () => (p.methode("seneca.stand", { geraet: "mac" }) as { gelernt: { nr: number }[] }).gelernt.map((g) => g.nr);
  assert.deepEqual(stand(), [Number(zweite.korrektur_nr), Number(r.korrektur_nr)]);
  const zurueck = (k: string, nr: unknown) => (p.methode("seneca.handeln", { kennung: k, geraet: "iphone", art: "lernen.zuruecknehmen", ziel: String(nr) }) as { ergebnis: string }).ergebnis;
  assert.equal(zurueck("z1", zweite.korrektur_nr), "angenommen");
  assert.equal(zurueck("z2", zweite.korrektur_nr), "abgelehnt:schon_zurueckgenommen");
  assert.deepEqual(stand(), [Number(r.korrektur_nr)]);
  p.nachricht(S, "m10", "Nie Anrufe vor 9 Uhr");
  const sperre = await p.werkzeug("seneca_lernen", S, "seneca", { nachricht_kennung: "m10", wortlaut: "Nie Anrufe vor 9 Uhr", ort: "sperre", ziel: "Ausgang Anruf", kern: "kein Anruf vor 9", aenderung: {} });
  const bau = auftraege(p.db, ["bereit"]).find((x) => String(x.titel).startsWith("Sperre im Ausgang"));
  uebergang(p.db, "auftrag", String(bau?.id), "verworfen", "test");
  assert.equal(zurueck("z3", sperre.korrektur_nr), "angenommen");
  assert.ok(auftraege(p.db, ["bereit"]).every((x) => !String(x.titel).startsWith("Sperre „kein Anruf")));
});

test("PF09 Statistik von selbst: zweite Standfrage, neue Datenart und neues Projekt werden ein Auftrag; ungesehen wird grau, Ansehen macht sie wieder aktiv", async () => {
  const p = ladePlugin();
  um("10:00");
  const statistikAuftraege = () => auftraege(p.db, ["bereit"]).filter((a) => a.arbeitsart === "statistik_anlegen");
  const frage = (satz: string) => p.werkzeug("seneca_statistik", S, "seneca", { art: "frage", thema: "Kniebeuge", satz, an: "trainer" });
  assert.match(String((await frage("Wie läuft die Kniebeuge?")).satz), /^Gemerkt/);
  assert.equal(statistikAuftraege().length, 0);
  spaeter(3 * 86400000);
  assert.match(String((await frage("Und, wie weit bin ich bei der Kniebeuge?")).satz), /Ich lege dir dafür eine Statistik an/);
  assert.deepEqual(statistikAuftraege().map((a) => [a.verantwortlich, a.quelle]), [["trainer", "eigene_idee"]]);
  await frage("Kniebeuge?");
  assert.equal(statistikAuftraege().length, 1);
  eintragSetzen(p.db, { art: "lauf", werte: { km: 5 }, zeit: um("07:00"), quelle: "iphone" });
  anlaesseJob(p.db);
  assert.equal(statistikAuftraege().length, 1);
  eintragSetzen(p.db, { art: "satz", werte: { u: "Kniebeuge", kg: 80, w: 5 }, zeit: um("08:00"), quelle: "garmin" });
  eintragSetzen(p.db, { art: "lauf", werte: { km: 6 }, zeit: um("09:00"), quelle: "iphone" });
  anlaesseJob(p.db);
  assert.deepEqual(statistikAuftraege().map((a) => a.titel).sort(), ["Statistik: daten satz:garmin", "Statistik: kniebeuge"]);
  await p.werkzeug("seneca_projekt", S, "seneca", { name: "Ultra", worum: "100 km am Stück bis Juni" });
  await p.werkzeug("seneca_projekt", S, "seneca", { name: "Ultra", satz: "läuft" });
  assert.equal(statistikAuftraege().filter((a) => a.titel === "Statistik: projekt ultra").length, 1);
  const id = anzeigeSetzen(p.db, { projekt: "Training", art: "statistik", titel: "Wochen-km", werte: { metrik: "lauf.km", grund: "Weg zu 100 km" }, besitzer: "trainer" });
  assert.match(String((await p.werkzeug("seneca_statistik", S, "seneca", { art: "sicht" })).satz), /Wochen-km“ \(Training, von trainer, aktiv\): Weg zu 100 km; angesehen nie/);
  rundgangVorbereiten(p.db, { verantwortlich: "seneca" }, spaeter(15 * 86400000));
  assert.equal(hole(p.db, "anzeige", id).zustand, "grau");
  assert.ok(fragen(p.db, "offen").some((f) => f.text === "Kann „Wochen-km“ weg?"));
  p.methode("seneca.handeln", { kennung: "sa1", geraet: "mac", art: "anzeige.angesehen", ziel: id });
  assert.equal(hole(p.db, "anzeige", id).zustand, "aktiv");
});
